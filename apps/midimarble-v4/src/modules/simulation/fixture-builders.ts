// M3 fixtures, built the way a user would with the assists. They need a simulation, so the documents
// are generated by `scripts/build-fixtures.ts` and committed; tests load the committed files.

/**
 * One marble, sixteen hits 0.4 s apart: the first platform tilted by hand, then Mirror, then Continue. At
 * half gravity a mirrored 0.3 s rhythm hops only about half a bar, so the bars would overlap.
 */
export function buildZigzagProject(simulate: TSimulateFn): TProject {
	let project = createBareRunProject({
		id: 'zigzag',
		title: 'Zigzag',
		end: 6.7,
		marbles: [{ x: 0, y: 0.6, releaseTime: 0, hitTimes: evenTimes(0.2, 0.4, 16) }]
	});
	const laneId = 'lane-1';
	// With the default kit's 9 cm bars and the default bounce, a 0.45 rad start mirrors into sixteen clean hits
	const first = createLinkedPiece('platform', laneId, 'hit-1-1', -0.45, { id: 'piece-1-1' });
	project = apply(project, [{ type: 'upsertEntity', entity: first }]);
	const [isMirrorOk, mirrorErr, mirrored] = mirrorPiece(project, simulate(project), laneId, {
		id: 'piece-1-2'
	});
	if (!isMirrorOk) throw mirrorErr;
	project = apply(project, mirrored.commands);
	const continued = continueSuggestions(project, simulate(project), laneId, {
		simulate,
		idFor: (hitId) => hitId.replace('hit', 'piece')
	});
	if (continued == null) throw new Error('Continue found no pattern');
	return apply(project, continued.commands, 0);
}

/**
 * One marble with two 1.5 s gaps. A rail bridges the first and a tunnel the second. Auto place sets the
 * platforms after each gap, which are placed by construction, so every hit stays on time.
 */
export function buildLongGapProject(simulate: TSimulateFn): TProject {
	let project = createBareRunProject({
		id: 'long-gap',
		title: 'Long gap',
		end: 5.2,
		marbles: [
			{ x: 0, y: 0.6, releaseTime: 0, hitTimes: [0.15, 0.45, 0.75, 2.25, 2.55, 2.85, 4.35, 4.65] }
		]
	});
	const laneId = 'lane-1';
	project = autoPlaceHits(project, laneId, ['hit-1-1', 'hit-1-2', 'hit-1-3'], simulate);
	const withRail = bridgeGap(project, laneId, 2, simulate, (candidate) => createRailForGap(candidate, simulate(candidate), laneId, 'hit-1-3', 'hit-1-4', { simulate, id: 'rail-1' }));
	if (withRail == null) throw new Error('No platform angle leaves room for the rail');
	project = autoPlaceHits(withRail, laneId, ['hit-1-4', 'hit-1-5', 'hit-1-6'], simulate);
	const withTunnel = bridgeGap(project, laneId, 5, simulate, (candidate) => createTunnelForGap(candidate, simulate(candidate), laneId, 'hit-1-6', 'hit-1-7', { simulate, id: 'tunnel-1' }));
	if (withTunnel == null) throw new Error('No platform angle leaves room for the tunnel');
	project = withTunnel;
	return apply(autoPlaceHits(project, laneId, ['hit-1-7', 'hit-1-8'], simulate), [], 0);
}

/**
 * One marble, seven platforms. The windmill is scenery: it is anchored to the trajectory a moment after the
 * third hit, so the marble strikes a blade in flight between two platforms and sets it turning without
 * sounding a note. Auto place sets the platforms after it. The first anchor delay that leaves Auto place an
 * answer for every later hit wins.
 */
export function buildWindmillProject(simulate: TSimulateFn): TProject {
	let start = createBareRunProject({
		id: 'windmill',
		title: 'Windmill',
		end: 2.6,
		marbles: [{ x: 0, y: 0.6, releaseTime: 0, hitTimes: evenTimes(0.15, 0.3, 7) }]
	});
	const laneId = 'lane-1';
	start = autoPlaceHits(start, laneId, ['hit-1-1', 'hit-1-2', 'hit-1-3'], simulate);
	// Blade 0 points along the angle from the hub; angles near π put the hub below and ahead of the marble,
	// clear of where it came from
	for (const angle of [-0.3, 2.8, 2.4, 0.3, 2.0, -2.8, 1.6, -2.4]) {
		for (const delay of [0.18, 0.15, 0.21, 0.12, 0.24, 0.09, 0.27]) {
			const windmill = createLinkedPiece('windmill', laneId, 'hit-1-3', angle, { id: 'windmill-1' });
			if (windmill.components.piece != null)
				windmill.components.piece.params = { ...windmill.components.piece.params, entryDelay: delay };
			const project = apply(start, [{ type: 'upsertEntity', entity: windmill }]);
			const run = simulate(project);
			const isPlaced = run.pieces.some((piece) => piece.entityId === 'windmill-1' && piece.status === 'placed');
			const struck = run.contacts.some((contact) => contact.otherEntityId === 'windmill-1');
			if (!isPlaced || !struck) continue;
			try {
				return apply(autoPlaceHits(project, laneId, ['hit-1-4', 'hit-1-5', 'hit-1-6', 'hit-1-7'], simulate), [], 0);
			} catch {
				// The next anchor sends the marble differently
			}
		}
	}
	throw new Error('No windmill anchor leaves room for the platforms after it');
}

/**
 * Two marbles thrown at each other collide head-on at about 0.18 s, then Build Track sets every platform, which also
 * keeps the marbles from meeting again. `scripts/build-fixtures.ts` runs it, as it lives with the app. Half a second
 * between notes leaves two narrow lanes room; at 0.4 s every tilt of one marble's second platform leaves the other no
 * spot, and with the film's folded clearance nothing fits.
 */
export function createTwoMarblesStart(): TProject {
	return createBareRunProject({
		id: 'two-marbles',
		title: 'Two marbles',
		end: 2.1,
		marbles: [
			{ x: -LANE_SPACING / 2, y: 0.6, releaseTime: 0, velocity: { x: 0.65, y: 0 }, hitTimes: [0.45, 0.95, 1.45] },
			{ x: LANE_SPACING / 2, y: 0.6, releaseTime: 0, velocity: { x: -0.65, y: 0 }, hitTimes: [0.55, 1.05, 1.55] }
		]
	});
}

/**
 * The gap piece after the platform at `index`: the platform turns the marble toward the frame centre, so the piece has
 * room, and the first of its tilts that leaves nothing struck twice or touching wins, or else the first that plays
 */
function bridgeGap(project: TProject, laneId: string, index: number, simulate: TSimulateFn, create: (candidate: TProject) => TResult<TGapPieceProposal, Error>): TProject | null {
	let first: TProject | null = null;
	for (const angle of [0.4, -0.4, 0.3, -0.3, 0.15, -0.15, 0.5, -0.5, 0.2, -0.2]) {
		const candidate = placeAngles(project, laneId, [angle], index);
		const [isOk, , piece] = create(candidate);
		if (!isOk || piece.check?.isDotInFrame !== true || !piece.check.isRunInFrame) continue;
		const bridged = apply(candidate, piece.commands);
		const run = simulate(bridged);
		first ??= bridged;
		// A long fall after a short ride isn't what a gap piece is for
		const entry = run.contacts.find((contact) => contact.otherEntityId === piece.entity.id);
		const gapEnd = run.hits.find((hit) => hit.targetTime > (entry?.time ?? Infinity))?.targetTime ?? Infinity;
		const lowest = Math.min(...(run.marbles[0]?.samples ?? []).filter((sample) => sample.time > (entry?.time ?? Infinity) && sample.time < gapEnd).map((sample) => sample.position.y));
		const isCarried = entry != null && lowest > entry.position.y - 0.4;
		if (isCarried && !extraStrikes(bridged, run).length && !touchingPairs(bridged, run).length && !rollingHits(bridged, run).length) return bridged;
	}
	return first;
}

/** Platforms at the lane's hits from `fromIndex` on with the given angles */
function placeAngles(project: TProject, laneId: string, angles: number[], fromIndex = 0): TProject {
	const lane = laneId.replace('lane-', '');
	return apply(
		project,
		angles.map((angle, i) => ({
			type: 'upsertEntity',
			entity: createLinkedPiece('platform', laneId, `hit-${lane}-${fromIndex + i + 1}`, angle, {
				id: `piece-${lane}-${fromIndex + i + 1}`
			})
		}))
	);
}

function autoPlaceHits(
	project: TProject,
	laneId: string,
	hitIds: string[],
	simulate: TSimulateFn
): TProject {
	let next = project;
	for (const hitId of hitIds) {
		const [isPlacedOk, placedErr, placed] = autoPlace(next, simulate(next), laneId, hitId, {
			simulate,
			id: hitId.replace('hit', 'piece')
		});
		if (!isPlacedOk) throw new Error(`${hitId}: ${placedErr.message}`);
		next = apply(next, placed.commands);
	}
	return next;
}

function apply(project: TProject, commands: TProjectCommand[], revision?: number): TProject {
	const [isAppliedOk, appliedErr, applied] = applyProjectCommands(project, commands);
	if (!isAppliedOk) throw appliedErr;
	if (revision != null) applied.revision = revision;
	return applied;
}

