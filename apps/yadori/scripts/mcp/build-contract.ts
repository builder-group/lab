import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { SCommands } from '../../src/modules/project/model/schema';

// Structural schema is generated; domain referential checks still run before Apply.
const contract = {
	format: 'yadori/project@3',
	commands: z.toJSONSchema(SCommands, { unrepresentable: 'any' }),
	guidance:
		'Submit small command batches at the saved base revision. Keep stable IDs. Add source URLs for researched facts; keep uncertain ratings unknown. Use review.add for findings. Commands are validated and dry-run in the UI before user approval; never write project files directly.'
};
writeIfChanged(
	fileURLToPath(new URL('../../src-tauri/src/command-contract.json', import.meta.url)),
	JSON.stringify(contract, null, 2) + '\n'
);

const assets = JSON.parse(
	readFileSync(
		fileURLToPath(new URL('../../src/modules/library/data/assets.json', import.meta.url)),
		'utf8'
	)
) as Array<{ id: string; relativePath: string }>;
const arms = assets
	.map(
		(asset) =>
			`${JSON.stringify(asset.id)} => Some(include_bytes!(${JSON.stringify('../../public/' + asset.relativePath)}).as_slice()),`
	)
	.join('\n');
const rust = execFileSync('rustfmt', ['--edition', '2021', '--emit', 'stdout'], {
	encoding: 'utf8',
	input: `// Generated by scripts/mcp/build-contract.ts; edit the catalog sources.\npub const CATALOG:&str=include_str!("../../src/modules/library/data/catalog.v1.json");\npub const ASSETS:&str=include_str!("../../src/modules/library/data/assets.json");\npub fn asset_bytes(id:&str)->Option<&'static [u8]>{match id {${arms} _=>None}}\n`
});
writeIfChanged(
	fileURLToPath(new URL('../../src-tauri/src/library_data.rs', import.meta.url)),
	rust
);
function writeIfChanged(path: string, content: string): void {
	if (existsSync(path) && readFileSync(path, 'utf8') === content) return;
	writeFileSync(path, content);
}
